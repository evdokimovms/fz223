
import re

CATEGORIES: dict[str, tuple[str, tuple[str, ...]]] = {
    "brand": ("Товарный знак / производитель",
              ("товарн", "знак", "марк", "эквивалент", "аналог", "патент", "полезн", "фирменн")),
    "origin": ("Страна происхождения", ("происхожден", "импорт", "отечествен", "иностран")),
    "standards": ("ТУ / стандарты", ("гост", "технические условия", "стандарт", "технический регламент")),
    "exclusive": ("Единственный поставщик", ("единственн", "исключительн")),
    "participants": ("Требования к участникам",
                     ("участник", "опыт", "квалификац", "лиценз", "сро", "дилер", "репутац")),
    "competition": ("Ограничение конкуренции", ("конкуренц", "равноправ", "дискриминац", "необоснованн")),
    "completeness": ("Полнота комплекта документации", ("документаци", "извещени", "должна содержать")),
    "price": ("Цена и обоснование", ("начальн", "максимальн", "нмц", "обоснован", "цена")),
    "payment": ("Оплата и сроки", ("оплат", "аванс", "рабочих дн")),
    "okpd": ("Код ОКПД 2", ("окпд",)),
    "contradiction": ("Противоречие в документе", ()),
    "incorrect_term": ("Некорректное условие", ()),
    "reference": ("Ссылки на документы и стандарты", ()),
    "general": ("Общие требования", ()),
}


def label(category: str) -> str:
    return (CATEGORIES.get(category) or (category.replace("_", " ").capitalize(),))[0]


def classify(text: str) -> str:
    t = (text or "").lower()
    best, best_n = "general", 0
    for cat, (_, kws) in CATEGORIES.items():
        n = sum(1 for k in kws if k in t)
        if n > best_n:
            best, best_n = cat, n
    return best


def slug(value: str) -> str:
    return re.sub(r"[^a-z_]", "", (value or "").lower().replace(" ", "_").replace("-", "_"))[:32]
